#!/usr/bin/env node
/**
 * gen-spaces-readme — write spaces/README.md from spaces/registry.json.
 *
 *   node scripts/gen-spaces-readme.mjs          # write
 *   node scripts/gen-spaces-readme.mjs --check  # exit 1 when the README is stale
 *
 * The README listed 29 of 45 spaces by hand and said "45" in one place and "43" in
 * another; generating it from the registry keeps the two from drifting.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const reg = JSON.parse(readFileSync(join(ROOT, 'spaces', 'registry.json'), 'utf8').replace(/^﻿/, ''));
const listable = reg.spaces.filter((e) => !e.internal);
const internal = reg.spaces.filter((e) => e.internal);
const price = (e) => (e.marketplace?.price_cents ? `$${(e.marketplace.price_cents / 100).toFixed(0)}` : 'free');
const folder = (e) => e.path ?? e.id;
const count = (s) => listable.filter((e) => e.status === s).length;

const out = [];
out.push('# NAVIG Spaces', '');
out.push('<!-- Generated by scripts/gen-spaces-readme.mjs from registry.json — edit the registry, then re-run. -->', '');
out.push('A **space** is a whole workshop: a folder with a `.navig/` holding the agents, skills,');
out.push('workflows, plans and example memory for one domain. Install one, then switch to it:', '');
out.push('```bash', 'navig space install github:navig-run/registry/spaces/<folder>', 'navig space use <folder>', '```', '');
out.push(`**${reg.spaces.length} spaces** — ${listable.length} listable (${count('active')} active, ${count('planned')} planned, ${count('labs')} labs, ${count('ready')} ready) and ${internal.length} internal templates.`, '');
out.push('| Status | Meaning |', '|---|---|');
out.push('| `active` | Ships working agents, skills and workflows |');
out.push('| `ready` | Complete, not yet in wide use |');
out.push('| `planned` | A designed scaffold — capabilities are still to be built; never sold |');
out.push('| `labs` | Experimental and opt-in; never sold |', '');

for (const [tier, blurb] of Object.entries(reg.tiers ?? {})) {
  const rows = listable.filter((e) => e.tier === tier);
  if (!rows.length) continue;
  out.push(`## ${tier[0].toUpperCase()}${tier.slice(1)}`, '', `${blurb}.`, '');
  out.push('| Space | Status | Price | What it is |', '|---|---|---|---|');
  for (const e of rows) out.push(`| [\`${folder(e)}\`](${folder(e)}/) | ${e.status} | ${price(e)} | ${e.tagline ?? ''} |`);
  out.push('');
}

const nested = reg.spaces.filter((e) => Array.isArray(e.sub_spaces) && e.sub_spaces.length);
if (nested.length) {
  out.push('## Nested spaces', '', 'Real spaces that live inside a parent space folder (not logical links):', '');
  out.push('| Parent | Path |', '|---|---|');
  for (const e of nested) for (const p of e.sub_spaces) out.push(`| \`${folder(e)}\` | \`${p}\` |`);
  out.push('');
}

out.push('## Templates (internal)', '');
for (const e of internal) out.push(`- [\`${folder(e)}\`](${folder(e)}/) — ${e.tagline ?? ''}`);
out.push('');

out.push('## Create a space', '');
out.push('```bash', 'cp -r empty-space/ my-space/            # the skeleton', '# edit my-space/.navig/space.json — id must equal the folder name', 'navig space doctor my-space              # check it', 'node ../scripts/check-registry.mjs      # the publish gate', '```', '');
out.push('The manifest fields are documented in [`schema.yaml`](schema.yaml). Every space ships a');
out.push('`LICENSE` (MIT), a `.navig/space.json`, and only *example* state under `.navig/memory/`,');
out.push('`.navig/inbox/` and `.navig/state/`.', '');
out.push('## Everyday commands', '', '```bash', 'navig space list', 'navig space use <folder>', 'navig space current', 'navig space doctor', '```', '');

const text = out.join('\n');
const file = join(ROOT, 'spaces', 'README.md');
if (process.argv.includes('--check')) {
  const cur = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  if (cur !== text) {
    console.error('spaces/README.md is stale — run: node scripts/gen-spaces-readme.mjs');
    process.exit(1);
  }
  console.log('spaces/README.md is current');
} else {
  writeFileSync(file, text);
  console.log(`wrote spaces/README.md (${reg.spaces.length} spaces)`);
}
